/**
 * «Frases por estructura» (v1.0): un módulo aparte de las unidades. Cada estructura junta ~20 frases
 * del día a día que repiten el mismo patrón con otros verbos, sujetos y situaciones.
 *
 * Formato de cada frase: [inglés, español]. En el inglés va entre {…} la parte de la estructura
 * (la que se completa en los ejercicios y se destaca en la explicación). Para sumar frases o
 * estructuras alcanza con agregar datos acá: el resto (explicación palabra por palabra, ejercicios,
 * repaso, combinación) sale solo.
 *
 * `keys`: explicación de las palabras propias de la estructura para el desglose palabra por palabra.
 * Las demás palabras se explican con el diccionario de la app.
 */
export interface Structure {
  id: string;
  level: Level;
  title: string;
  /** Fórmula general. */
  pattern: string;
  /** Explicación corta en español. */
  explain: string[];
  /** Tabla de formas (cambios según el sujeto o el tiempo). */
  table?: { head: string[]; rows: string[][] };
  keys: Record<string, string>;
  /** Para reconocer la estructura en un texto libre (ejercicio de combinar). */
  detect: RegExp;
  /** Situaciones para escribir directamente en inglés: [consigna, ejemplo]. */
  tasks: [string, string][];
  phrases: [string, string][];
}

